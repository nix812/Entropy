"""v4.7 Music Studio: opens from the hangar and the pause menu, controls switch to Custom, genres/faders/FX/favourites work
and persist, and it fits at phone size. usage: python3 studioshot.py [W H]"""
import pathlib, sys, mkpage
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).parent.parent
out = root / 'test' / 'out'
W, H = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (852, 393)
mkpage.mk()
errs, fails = [], []
def check(c, m):
    if not c: fails.append(m)
with sync_playwright() as p:
    b = p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required']); pg = b.new_page(viewport={'width': W, 'height': H}, device_scale_factor=2, has_touch=True)
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('file://' + str(out / 'page.html')); pg.wait_for_timeout(400)
    pg.evaluate('() => { PROF.bestWave = 40; PROF.seenHelp = true; PROF.xp = 900000; PROF.runs = 3; PROF.seenVer = VERSION; PROF.settings.briefings = "off"; UI.renderHangar(); }')
    pg.screenshot(path=str(out / f'studio_hangar_{W}.png'))
    pg.click('#bStudio'); pg.wait_for_timeout(1500)
    check(pg.evaluate('() => !!document.querySelector(".card.studio")'), 'studio did not open')
    check(pg.evaluate('() => !SFX.music.config.custom'), 'should start in Default')
    pg.screenshot(path=str(out / f'studio_default_{W}.png'))
    ov = pg.evaluate('() => { const c = document.querySelector(".card.studio"); return c.scrollWidth - c.clientWidth; }')
    check(ov <= 1, f'studio overflows horizontally by {ov}')
    pg.click('[data-act=stGenre][data-v=techno]'); pg.wait_for_timeout(300)
    st = pg.evaluate('() => ({ c: SFX.music.config.custom, g: SFX.music.config.genres.slice() })')
    check(st['c'] and 'techno' in st['g'] and 'lofi' in st['g'], f'genre pick wrong: {st}')
    pg.wait_for_timeout(2600)
    g = pg.evaluate('() => SFX.music.piece.genre')
    check(g == 'techno', f'expected techno after skip, got {g}')
    pg.query_selector('.fader[data-ch=drums]').scroll_into_view_if_needed(); pg.wait_for_timeout(100)
    f = pg.query_selector('.fader[data-ch=drums]').bounding_box()
    pg.mouse.move(f['x'] + f['width'] / 2, f['y'] + 10); pg.mouse.down(); pg.mouse.move(f['x'] + f['width'] / 2, f['y'] + f['height'] + 20, steps=4); pg.mouse.up()
    check(pg.evaluate('() => SFX.music.config.mix.drums') < 0.05, 'fader did not pull drums down')
    pg.click('[data-act=stMute][data-v=bass]')
    check(pg.evaluate('() => !!SFX.music.config.mute.bass'), 'mute failed')
    pg.evaluate('() => { const e = document.querySelector("#stEnergy"); e.value = 0.9; e.dispatchEvent(new Event("input")); e.dispatchEvent(new Event("change")); }')
    check(abs(pg.evaluate('() => SFX.music.config.energy') - 0.9) < 0.01, 'energy slider')
    pg.click('[data-act=stSave]'); pg.wait_for_timeout(300)
    check(pg.evaluate('() => SFX.music.config.favs.length') == 1, 'save failed')
    check(pg.evaluate('() => PROF.settings.studio === SFX.music.config'), 'studio not persisted in PROF')
    pg.wait_for_timeout(800)
    pg.screenshot(path=str(out / f'studio_custom_{W}.png'))
    pg.evaluate('() => document.querySelector(".card.studio").scrollTop = 9999'); pg.wait_for_timeout(200)
    pg.screenshot(path=str(out / f'studio_bottom_{W}.png'))
    saved = pg.evaluate('() => { const P = Save.merge(JSON.parse(JSON.stringify(PROF))); return { g: P.settings.studio.genres, f: P.settings.studio.favs.length, d: P.settings.studio.mix.drums }; }')
    check(saved['f'] == 1 and 'techno' in saved['g'], f'save merge lost studio: {saved}')
    pg.click('.foot [data-act=stClose]'); pg.wait_for_timeout(200)
    check(pg.evaluate('() => !UI.modalOpen'), 'close failed')
    pg.click('#bLaunch'); pg.wait_for_timeout(200); pg.click('[data-act=launch]'); pg.wait_for_timeout(600)
    pg.click('#bPause'); pg.wait_for_timeout(200); pg.click('[data-act=studio]'); pg.wait_for_timeout(300)
    check(pg.evaluate('() => G.paused && UI.modalOpen === "studio"'), 'pause -> studio failed')
    pg.click('[data-act=stMode][data-v="0"]'); pg.wait_for_timeout(200)
    check(pg.evaluate('() => !SFX.music.config.custom'), 'Default toggle failed')
    pg.click('.foot [data-act=stClose]'); pg.wait_for_timeout(200)
    check(pg.evaluate('() => UI.modalOpen === "pause"'), 'did not return to pause')
    b.close()
print('FAILS:', fails); print('ERRORS:', errs[:5])
