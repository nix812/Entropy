    ok('the Compose tab is there from the start', pg.evaluate('() => SFX.music.config.composer && document.querySelectorAll(".sttabs .chip").length === 3'))
    act(pg, '[data-act=stTab][data-v=compose]'); pg.wait_for_timeout(300)
    ok('Compose opens', pg.evaluate('() => document.querySelector(".sttabs .chip.on").textContent === "Compose"'))
